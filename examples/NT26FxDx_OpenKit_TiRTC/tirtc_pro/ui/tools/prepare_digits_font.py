#!/usr/bin/env python3
"""Preserve the SDK Montserrat 48 glyphs used by Pro's clock/binding code.

Default: read-only verification. --write regenerates the two product files.
--cc PATH also compares real LVGL glyph lookup, metrics, pixels and kerning
against the original SDK font using a temporary native executable.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import tempfile
import sys
from pathlib import Path

UI = Path(__file__).resolve().parents[1]
ROOT = UI.parents[3]
LVGL = ROOT / "components/thirdparty/lvgl/lvgl-8.3.10"
SOURCE = LVGL / "src/font/lv_font_montserrat_48.c"
OUTPUT = UI / "font/tirtc_font_digits_48.c"
HEADER = OUTPUT.with_suffix(".h")
sys.path.insert(0, str(UI.parent / "resource_store"))
from font_resources import externalize_digits
CHARACTERS = " -0123456789:"
FIELDS = ("bitmap_index", "adv_w", "box_w", "box_h", "ofs_x", "ofs_y")


def body(text: str, name: str) -> str:
    match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not match:
        raise ValueError("Missing array: " + name)
    return re.sub(r"/\*.*?\*/", "", match[1], flags=re.S)


def numbers(text: str, name: str) -> list[int]:
    return [int(value, 0) for value in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body(text, name))]


def glyphs(text: str) -> list[dict]:
    return [dict((key, int(value)) for key, value in re.findall(r"\.(\w+)\s*=\s*(-?\d+)", row))
            for row in re.findall(r"\{([^}]+)\}", body(text, "glyph_dsc"))]


def array(name: str, kind: str, values: list[int], hexadecimal: bool = False) -> str:
    rendered = [f"0x{x:02x}" if hexadecimal else str(x) for x in values]
    lines = ["    " + ", ".join(rendered[i:i + 16]) + "," for i in range(0, len(rendered), 16)]
    return f"static const {kind} {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def generate(source: str) -> tuple[str, str]:
    # Reject a changed SDK format rather than silently creating wrong glyph IDs.
    if not re.search(r"\.range_start = 32, \.range_length = 95, \.glyph_id_start = 1", source):
        raise ValueError("SDK ASCII cmap changed")
    old = glyphs(source)
    bitmap = numbers(source, "glyph_bitmap")
    left = numbers(source, "kern_left_class_mapping")
    right = numbers(source, "kern_right_class_mapping")
    pairs = numbers(source, "kern_class_values")
    right_count = int(re.search(r"\.right_class_cnt\s*=\s*(\d+)", source)[1])
    selected = [ord(character) - 32 + 1 for character in CHARACTERS]
    kept = [dict(old[0])]
    pixels = []
    for index in selected:
        glyph = dict(old[index])
        start = glyph["bitmap_index"]
        count = (glyph["box_w"] * glyph["box_h"] + 1) // 2
        glyph["bitmap_index"] = len(pixels)
        pixels.extend(bitmap[start:start + count])
        kept.append(glyph)
    # Reindex only the classes used by retained glyphs; preserve exact values.
    left_classes = sorted(set(left[index] for index in selected) - {0})
    right_classes = sorted(set(right[index] for index in selected) - {0})
    left_ids = {value: index + 1 for index, value in enumerate(left_classes)}
    right_ids = {value: index + 1 for index, value in enumerate(right_classes)}
    compact_pairs = [pairs[(l - 1) * right_count + r - 1]
                     for l in left_classes for r in right_classes]
    output = ["/* Generated by ui/tools/prepare_digits_font.py; do not edit.\n"
              " * Subset of LVGL 8.3.10 src/font/lv_font_montserrat_48.c.\n"
              " * Original glyph pixels/metrics/kerning; SDK source is unchanged.\n"
              f" * SDK source SHA-256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}\n"
              " * LVGL copyright/license: components/thirdparty/lvgl/lvgl-8.3.10/LICENCE.txt\n"
              " */\n#include \"tirtc_font_digits_48.h\"\n",
              array("glyph_bitmap", "uint8_t", pixels, True),
              "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"]
    for glyph in kept:
        output.append("    {" + ", ".join(f".{field} = {glyph[field]}" for field in FIELDS) + "},")
    output += ["};\n", array("unicode_list", "uint16_t", [ord(c) - 32 for c in CHARACTERS]),
               # Sparse lookup also safely rejects characters immediately after
               # a range on SDK LVGL versions with an inclusive range check.
               "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
               "    {.range_start = 32, .range_length = 27, .glyph_id_start = 1,",
               "     .unicode_list = unicode_list, .list_length = 13,",
               "     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},", "};\n",
               array("kern_left_class_mapping", "uint8_t", [0] + [left_ids.get(left[i], 0) for i in selected]),
               array("kern_right_class_mapping", "uint8_t", [0] + [right_ids.get(right[i], 0) for i in selected]),
               array("kern_class_values", "int8_t", compact_pairs),
               "static const lv_font_fmt_txt_kern_classes_t kern_classes = {",
               "    .class_pair_values = kern_class_values,",
               "    .left_class_mapping = kern_left_class_mapping,",
               "    .right_class_mapping = kern_right_class_mapping,",
               f"    .left_class_cnt = {len(left_classes)}, .right_class_cnt = {len(right_classes)},",
               "};\n", "static lv_font_fmt_txt_glyph_cache_t cache;",
               "static const lv_font_fmt_txt_dsc_t font_dsc = {",
               "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
               "    .kern_dsc = &kern_classes, .kern_scale = 16, .cmap_num = 1,",
               "    .bpp = 4, .kern_classes = 1, .bitmap_format = 0, .cache = &cache,", "};\n",
               "const lv_font_t tirtc_font_digits_48 = {",
               "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
               "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
               "    .line_height = 52, .base_line = 9, .subpx = LV_FONT_SUBPX_NONE,",
               "    .underline_position = -4, .underline_thickness = 2, .dsc = &font_dsc,", "};\n"]
    header = "#pragma once\n#include \"lvgl.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nLV_FONT_DECLARE(tirtc_font_digits_48);\n#ifdef TIRTC_EXTERNAL_UI_ASSETS\n/* Resource worker only, before exposing this font to LVGL. */\nint tirtc_font_digits_load_external(void (*progress)(uint32_t));\n#endif\n#ifdef __cplusplus\n}\n#endif\n"
    return externalize_digits("\n".join(output)), header


def verify_tables(source: str, subset: str) -> None:
    original, compact = glyphs(source), glyphs(subset)
    bitmap, pixels = numbers(source, "glyph_bitmap"), numbers(subset, "glyph_bitmap")
    def read_kerning(text: str) -> tuple:
        return (numbers(text, "kern_left_class_mapping"), numbers(text, "kern_right_class_mapping"),
                numbers(text, "kern_class_values"), int(re.search(r"\.right_class_cnt\s*=\s*(\d+)", text)[1]))
    def kern(tables: tuple, first: int, second: int) -> int:
        left, right = tables[0][first], tables[1][second]
        return tables[2][(left - 1) * tables[3] + right - 1] if left and right else 0
    old_kern, new_kern = read_kerning(source), read_kerning(subset)
    for index, character in enumerate(CHARACTERS, 1):
        old = original[ord(character) - 31]
        new = compact[index]
        if any(old[field] != new[field] for field in FIELDS[1:]):
            raise ValueError("Glyph metrics differ: " + repr(character))
        count = (old["box_w"] * old["box_h"] + 1) // 2
        if bitmap[old["bitmap_index"]:old["bitmap_index"] + count] != pixels[new["bitmap_index"]:new["bitmap_index"] + count]:
            raise ValueError("Glyph pixels differ: " + repr(character))
        for other_index, other in enumerate(CHARACTERS, 1):
            if kern(old_kern, ord(character) - 31, ord(other) - 31) != kern(new_kern, index, other_index):
                raise ValueError("Kerning differs: " + repr(character + other))
    print(f"PASS tables: {len(CHARACTERS)} glyphs, {len(CHARACTERS) ** 2} pairs, {len(pixels)} bitmap bytes")


def verify_lvgl(compiler: str) -> None:
    checker = r'''#include <stdio.h>
#include <string.h>
#include "font/tirtc_font_digits_48.h"
static const char required[] = " -0123456789:";
int main(void) {
    const lv_font_t *old = &lv_font_montserrat_48, *sub = &tirtc_font_digits_48;
    if (old->line_height != sub->line_height || old->base_line != sub->base_line ||
        old->subpx != sub->subpx || old->underline_position != sub->underline_position ||
        old->underline_thickness != sub->underline_thickness) return 1;
    unsigned checked = 0;
    for (unsigned i = 0; i < sizeof(required) - 1; ++i) {
        /* Include end-of-text as the next character, testing zero kerning. */
        for (unsigned j = 0; j < sizeof(required); ++j) {
            lv_font_glyph_dsc_t a = {0}, b = {0};
            if (!lv_font_get_glyph_dsc(old, &a, required[i], required[j]) ||
                !lv_font_get_glyph_dsc(sub, &b, required[i], required[j])) return 2;
            if (a.is_placeholder || b.is_placeholder || a.resolved_font != old || b.resolved_font != sub) return 3;
            if (a.adv_w != b.adv_w || a.box_w != b.box_w || a.box_h != b.box_h ||
                a.ofs_x != b.ofs_x || a.ofs_y != b.ofs_y || a.bpp != b.bpp) return 4;
            unsigned bytes = (a.box_w * a.box_h * a.bpp + 7) / 8;
            if (bytes && memcmp(lv_font_get_glyph_bitmap(old, required[i]),
                                lv_font_get_glyph_bitmap(sub, required[i]), bytes)) return 5;
            ++checked;
        }
    }
    const uint32_t missing[] = {0, '!', '.', '/', ';', 'A', 0x4e2d, 0xffffffff};
    for (unsigned i = 0; i < sizeof(missing) / sizeof(missing[0]); ++i) {
        lv_font_glyph_dsc_t dsc = {0};
        if (sub->get_glyph_dsc(sub, &dsc, missing[i], 0) ||
            sub->get_glyph_bitmap(sub, missing[i])) return 6;
    }
    printf("PASS real LVGL: %u glyph/pair/end-of-text cases\n", checked);
    return 0;
}
'''
    with tempfile.TemporaryDirectory(prefix="pro-digits-font-") as name:
        directory = Path(name)
        source, binary = directory / "verify.c", directory / "verify.exe"
        source.write_text(checker, encoding="utf-8")
        config = directory / "lv_conf.h"
        config.write_text((UI / "lv_conf.h").read_text(encoding="utf-8").replace(
            "#define LV_FONT_MONTSERRAT_48 0", "#define LV_FONT_MONTSERRAT_48 1"), encoding="utf-8")
        files = [source, SOURCE, OUTPUT, LVGL / "src/font/lv_font.c",
                 LVGL / "src/font/lv_font_fmt_txt.c", LVGL / "src/misc/lv_utils.c"]
        command = [compiler] + (["cc"] if Path(compiler).stem.lower() == "zig" else [])
        subprocess.run(command + ["-std=c99", "-O2", "-DLV_CONF_INCLUDE_SIMPLE",
                       "-I" + str(directory), "-I" + str(UI), "-I" + str(LVGL),
                       *map(str, files), "-o", str(binary)], check=True, timeout=120)
        subprocess.run([str(binary)], check=True, timeout=20)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--cc", help="Optional native compiler executable; Zig is supported")
    args = parser.parse_args()
    source = SOURCE.read_text(encoding="utf-8")
    output, header = generate(source)
    if args.write:
        OUTPUT.write_text(output, encoding="utf-8", newline="\n")
        HEADER.write_text(header, encoding="utf-8", newline="\n")
    if OUTPUT.read_text(encoding="utf-8") != output or HEADER.read_text(encoding="utf-8") != header:
        raise ValueError("Generated font is stale; run --write")
    verify_tables(source, OUTPUT.read_text(encoding="utf-8"))
    if args.cc:
        verify_lvgl(args.cc)


if __name__ == "__main__":
    main()
