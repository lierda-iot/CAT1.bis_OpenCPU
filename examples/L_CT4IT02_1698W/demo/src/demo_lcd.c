osMessageQueueId_t touchMsgid = NULL;

static void lcd_event_callback(void) {}

void tp_touch_callback(liot_tp_touch_data_t *data, void *ctx)
{
    liot_trace("[TP]touch");
    (void)ctx;
    for (uint8_t i = 0; i < data->touch_cnt; i++) {
        liot_trace("[TP] touch%d: evt=%d x=%d y=%d",
                        data->point[i].id,
                        data->point[i].event,
                        data->point[i].x,
                        data->point[i].y);
        osMessageQueuePut(touchMsgid, data, 0, 0);
    }
}

void tp_gesture_callback(liot_tp_gesture_data_t *data, void *ctx)
{
    (void)ctx;
    liot_trace("[TP] gesture: %d @%lu",
                    data->gesture, (unsigned long)data->timestamp_ms);
}

