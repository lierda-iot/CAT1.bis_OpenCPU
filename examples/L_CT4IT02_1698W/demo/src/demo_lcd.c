{
    liot_trace("[TP] INT triggered");
}

void tp_init(void)
{
    liot_tp_config_t tp_cfg = {
        .interface_type = LIOT_TP_IF_I2C,
        .i2c = {
            .num      = 1,
            .sda      = 66,
            .scl      = 57,
            .addr     = (0x2c),
            .scl_func = 3,
            .sda_func = 2,
        },
        .rst = {
            .pin        = 28,
            .delay_ms   = 100,
            .active_low = 1,
        },
        .int_pin = {
            .pin    = 19,
            .signal = L_INT_EDGE_FALL,
            .pull   = LIOT_FORCE_PULL_UP,
        },
        .sensor = &g_liot_tp_bl6178,
        .fw_auto_update = 0,
    };

    touchMsgid = osMessageQueueNew(1, sizeof(liot_tp_touch_data_t), NULL);

    liot_tp_handle_t tp;
reinit:
    Liot_SetPinFunc(66,2);
    Liot_SetPinFunc(57,3);
    liot_I2cInit(1, LIOT_STANDARD_MODE);
    osDelay(1000);
    ctp_bl_ts_init(tp);

    tp = liot_tp_init(&tp_cfg);
    if (!tp) {
        liot_trace("[TP] init failed!");
        osDelay(1000);
        goto reinit;
    }
    liot_trace("[TP] init ok");
    
    extern const unsigned char fwbin[];
    // liot_tp_update_firmware(tp, fwbin, 0x7B8C);

//     /* 3. 读取IC信息 */
//     uint8_t ic_info[4] = {0};
//     if (liot_tp_get_ic_info(tp, ic_info, sizeof(ic_info)) == LIOT_TP_SUCCESS) {
//         liot_trace("[TP] IC info: chip_id=0x%x fw_ver=0x%x proj_id=0x%x lpm=0x%x",
//                         ic_info[0], ic_info[1], ic_info[2], ic_info[3]);
//     }

//     /* 4. 注册触摸/手势回调 */
    liot_tp_register_int_callback(tp,
                                    tp_touch_callback,
                                    tp_gesture_callback,
                                    NULL, NULL);

//     /* 5. 启动INT中断轮询 */
    liot_tp_enable_int(tp, true);
    liot_trace("[TP] INT enabled, waiting for touch...");

    liot_intcb_t intcb = {
        .arg = NULL,
        .callback = tp_int_callback,
        .signal = L_INT_EDGE_FALL,
    };

    Liot_SetPinFunc(6, L_PIN_FUNC_0);
    Liot_GpioInit(L_GPIO_21, L_IO_INPUT, L_IO_HIGH, &intcb);
    Liot_GpioIntEnable();

}

void liot_lcd_demo_thread(void *argv)
{

    uint16_t last_x = 0, last_y = 0;

    // QSPI interface: supports ST77916, EC718M only
    liot_hal_lcdDev_t *lcdDev = &liot_gc9b72_dev;

    liot_lcd_config_t cfg = {
        .interface = {
            .type = LIOT_LCD_INTERFACE_QSPI,
            .qspi = {
                .num = LIOT_LSPI_PORT2,
                .cmd_line = LIOT_QSPI_DATA_LINE_1,
                .data_line = LIOT_QSPI_DATA_LINE_4,
                .instruction = 0x32,
                .speed = LIOT_LSPI_51MHZ,
                .sync = true,
                .cs = LIOT_LSPI_CS0,
                .cb = lcd_event_callback,
            },
            .blk.type = LIOT_LCD_BACKLIGHT_PWM,
            .blk.pin = 100,
            .blk.pwm_num = LIOT_PWM_0,
            .rst.pin = 78,
            .rst.delay = 100,
        },
        .lcdDev = lcdDev,
    };

    liot_rtos_task_sleep_ms(5000);
    liot_trace("==== lcd demo start ====");
    Liot_AonPowerCtl(true);
    Liot_SetVoltage(L_DOMAIN_ALL, L_VOLT_3_30V);
    LiotSleepModeCfg_t mode_cfg = {LIOT_SLEEP_MODE_NORMAL};
    Liot_SleepSetMode(&mode_cfg);
    //LDO Ctrl
    Liot_GpioInit(L_GPIO_25, L_IO_OUTPUT, L_IO_HIGH, NULL);
    Liot_GpioInit(L_GPIO_27, L_IO_OUTPUT, L_IO_HIGH, NULL);

    liot_lcd_handle_t lcd = liot_lcd_init(&cfg);

    osStatus_t osret = 0;
    liot_tp_touch_data_t tpdata = {0};
    tp_init();

    // brightness test
    liot_lcd_set_brightness(lcd, 100);
    liot_rtos_task_sleep_ms(1000);
    liot_lcd_set_brightness(lcd, 80);
    liot_rtos_task_sleep_ms(1000);
    liot_lcd_set_brightness(lcd, 60);
    liot_rtos_task_sleep_ms(1000);
    liot_lcd_set_brightness(lcd, 40);
    liot_rtos_task_sleep_ms(1000);
    liot_lcd_set_brightness(lcd, 20);
    liot_rtos_task_sleep_ms(1000);

    uint32_t width = 0, height = 0;
    if(lcdDev->info.direction == LIOT_LCD_DIR_0_ANGLE || lcdDev->info.direction == LIOT_LCD_DIR_180_ANGLE)
    {
        width = lcdDev->info.width;
        height = lcdDev->info.height;
    }
    else
    {
        width = lcdDev->info.height;
        height = lcdDev->info.width;
    }
    // 画线
    liot_lcd_clear_screen(lcd, RED);
    liot_lcd_refresh(lcd);
    liot_lcd_draw_line(lcd, 0, height / 2, width, height / 2, BLUE);
    liot_lcd_draw_line(lcd, width / 2, 0, width / 2, height, BLUE);
    liot_lcd_refresh(lcd);

    // 显示图片
    liot_lcd_write(lcd, 0, 0, 100-1, 60-1, (uint8_t *)Lierda_logo);

    // circle test
    liot_lcd_draw_circle(lcd, width / 2, height / 2, 30, GREEN);
    liot_lcd_draw_circle(lcd, width / 2, height / 2, 60, GREEN);
    liot_lcd_draw_rectangle(lcd, (width / 2) - 30, (height / 2) - 30, (width / 2) + 30, (height / 2) + 30, BLACK);
    liot_lcd_draw_rectangle(lcd, (width / 2) - 60, (height / 2) - 60, (width / 2) + 60, (height / 2) + 60, BLACK);
    liot_lcd_refresh(lcd);

    liot_rtos_task_sleep_ms(3000);
    liot_lcd_clear_screen(lcd, WHITE);

    while(1)
    {

        osret = osMessageQueueGet(touchMsgid, &tpdata, NULL, 1);
        if(osret == osOK)
        {
            liot_lcd_draw_circle(lcd, last_x, last_y, 10, BLUE);
            liot_lcd_refresh(lcd);
            liot_lcd_draw_circle(lcd, tpdata.point[0].x, tpdata.point[0].y, 10, RED);
            liot_lcd_refresh(lcd);
            last_x = tpdata.point[0].x;
            last_y = tpdata.point[0].y;
        }
    }
}
